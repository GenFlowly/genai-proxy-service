package com.genflowly.activity.instruction

import com.genflowly.Routes
import com.genflowly.models.api.CreateInstructionRequest
import com.genflowly.models.api.ErrorResponse
import com.genflowly.models.api.InstructionResponse
import com.genflowly.utils.bearerToken
import com.genflowly.utils.requireAuthenticatedCustomerId
import io.github.smiley4.ktoropenapi.post
import io.ktor.http.HttpStatusCode
import io.ktor.server.auth.authenticate
import io.ktor.server.request.receive
import io.ktor.server.response.respond
import io.ktor.server.routing.Route
import org.slf4j.LoggerFactory
import com.genflowly.service.InstructionService

import com.genflowly.service.CustomerProfileService

private val logger = LoggerFactory.getLogger("CreateInstructionRoute")

fun Route.registerCreateInstructionRoutes(
    instructionService: InstructionService,
    customerProfileService: CustomerProfileService
) {
    authenticate("auth0", "apiKey") {
        post(Routes.CREATE_INSTRUCTION, {
            tags("Instructions")
            summary = "Create or update an instruction"
            description = "Creates a new instruction (persona), or a new version of an existing one " +
                    "when existingInstructionId is set. Persona metadata (icon, color, tags, category) " +
                    "is generated by AI; the name is AI-generated unless instructionName is provided."
            request {
                body<CreateInstructionRequest> {
                    description = "Instruction text and optional name / existing instruction id"
                    required = true
                }
            }
            response {
                code(HttpStatusCode.OK) {
                    description = "The stored instruction, including its id and version"
                    body<InstructionResponse>()
                }
                code(HttpStatusCode.InternalServerError) {
                    description = "Unexpected server error"
                    body<ErrorResponse>()
                }
            }
        }) {
            try {
                val customerId = call.requireAuthenticatedCustomerId(customerProfileService)
                val request = call.receive<CreateInstructionRequest>()
                val token = call.bearerToken()

                val response = instructionService.createInstructionWithGeneratedPersona(
                    customerId = customerId,
                    instructionName = request.instructionName,
                    instruction = request.instruction,
                    existingInstructionId = request.existingInstructionId,
                    bearerToken = token
                )

                call.respond(response)

            } catch (e: Exception) {
                logger.error(
                    "Unexpected error in Create Instruction controller: {}",
                    e.message,
                    e
                )
                call.respond(
                    HttpStatusCode.InternalServerError,
                    mapOf("error" to "Internal server error: ${e.message}")
                )
            }
        }
    }
}