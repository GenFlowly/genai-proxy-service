        for depth, chroma in ((8, 420), (10, 420), (8, 444), (10, 422), (10, 444)):
            im.info.update(bit_depth=depth, chroma=chroma)
            costs[(depth, chroma)] = image_normalize._decode_cost_per_pixel(im, "HEIF")
